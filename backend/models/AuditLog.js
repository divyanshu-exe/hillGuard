const mongoose = require('mongoose');

const auditLogSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    userName: {
      type: String,
      required: true
    },
    userRole: {
      type: String,
      required: true
    },
    action: {
      type: String,
      required: true,
      index: true // e.g. 'VERIFY_REPORT', 'REJECT_REPORT', 'UPDATE_ROAD_STATUS', 'MANUAL_TELEMETRY', 'SIMULATOR_SCENARIO'
    },
    targetEntity: {
      type: String,
      required: true // e.g. 'Report', 'Road', 'SensorNode', 'Alert'
    },
    targetId: {
      type: String,
      required: true
    },
    details: {
      type: mongoose.Schema.Types.Mixed,
      default: {}
    },
    ipAddress: {
      type: String,
      default: '127.0.0.1'
    }
  },
  {
    timestamps: true
  }
);

auditLogSchema.index({ createdAt: -1 });

module.exports = mongoose.model('AuditLog', auditLogSchema);
